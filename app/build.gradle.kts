// Release signing comes from the environment so no secret is ever committed (see README, "Releasing").
val releaseKeystore: String? = System.getenv("RELEASE_KEYSTORE_PATH")

android {
    namespace = "app.archivefetcher"
    compileSdk = 36

    defaultConfig {
        applicationId = "app.archivefetcher"
        minSdk = 24
        targetSdk = 35
        // The release workflow passes the tag as -PversionName=1.2.3 and the run number as -PversionCode=N.
        versionCode = (findProperty("versionCode") as String?)?.toIntOrNull() ?: 5
        versionName = (findProperty("versionName") as String?) ?: "1.3.0"
    }

    signingConfigs {
        if (releaseKeystore != null) {
            create("release") {
                storeFile = file(releaseKeystore)
                storePassword = System.getenv("RELEASE_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("RELEASE_KEY_ALIAS")
                keyPassword = System.getenv("RELEASE_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            // R8 shrinks and obfuscates the code, drops unused resources and strips android.util.Log calls.
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (releaseKeystore != null) signingConfig = signingConfigs.getByName("release")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
}

